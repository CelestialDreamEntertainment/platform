import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { defineApp, route } from '@sbwp/runtime';
import { describe, expect, it } from 'vitest';
import { fixtureApp } from '../test/fixture.js';
import { routesTypes, typesFile, writeRoutesTypes } from './types.js';

const app = defineApp({
    name: 'events',
    scopes: ['events:guest'],
    baseScope: 'events:guest',
    routes: [
        route('GET', '/events/:id', './handlers/getEvent'),
        route('GET', '/a', './handlers/a.ts'),
        route('GET', '/b', './handlers/b.tsx'),
        route('GET', '/c', './handlers/c.js')
    ]
});

describe('routesTypes', () => {
    it('imports each handler type and maps routes to them', () => {
        expect(routesTypes(app, 'api/app.ts')).toBe(
            [
                "// Generated by `sbwp types` from app.ts. Don't edit it: `sbwp dev` and `sbwp types` rewrite it.",
                "import type { handler as r0 } from './handlers/getEvent.js';",
                "import type { handler as r1 } from './handlers/a.js';",
                "import type { handler as r2 } from './handlers/b.jsx';",
                "import type { handler as r3 } from './handlers/c.js';",
                '',
                '/** Every events route, for `createClient<Routes>()`. */',
                'export type Routes = {',
                "    'GET /events/:id': typeof r0;",
                "    'GET /a': typeof r1;",
                "    'GET /b': typeof r2;",
                "    'GET /c': typeof r3;",
                '};',
                ''
            ].join('\n')
        );
    });

    it('goes next to the manifest', () => {
        expect(typesFile('backend/manifest.ts')).toBe('backend/routes.gen.ts');
    });
});

describe('writeRoutesTypes', () => {
    it('writes the file once, then reports it up to date', async () => {
        const dir = await fixtureApp();
        await writeFile(join(dir, 'api/routes.gen.ts'), 'stale');
        expect(await writeRoutesTypes({ appDir: dir, check: true })).toEqual({
            file: 'api/routes.gen.ts',
            changed: true
        });
        expect(await readFile(join(dir, 'api/routes.gen.ts'), 'utf8')).toBe('stale');
        expect(await writeRoutesTypes({ appDir: dir })).toEqual({
            file: 'api/routes.gen.ts',
            changed: true
        });
        expect(await readFile(join(dir, 'api/routes.gen.ts'), 'utf8')).toContain(
            "'GET /health': typeof r3;"
        );
        expect(await writeRoutesTypes({ appDir: dir, check: true })).toEqual({
            file: 'api/routes.gen.ts',
            changed: false
        });
    });

    it('keeps the committed fixture file current', async () => {
        const dir = new URL('../test/fixtures/events', import.meta.url).pathname;
        expect((await writeRoutesTypes({ appDir: dir, check: true })).changed).toBe(false);
    });
});
