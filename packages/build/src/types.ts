import { readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import type { AppManifest } from '@sbwp/runtime';
import { DEFAULT_MANIFEST, loadManifest } from './build.js';

/** Where the generated types go: next to the manifest. It's committed, so CI can type-check the frontend. */
export const typesFile = (manifest: string): string => join(dirname(manifest), 'routes.gen.ts');

const importPath = (handler: string): string =>
    /\.[cm]?[jt]sx?$/.test(handler) ? handler.replace(/\.ts(x?)$/, '.js$1') : `${handler}.js`;

/** The `Routes` type the web package's `createClient<Routes>()` takes, generated from the manifest. */
export const routesTypes = (app: AppManifest, manifest: string): string => {
    const lines = [
        `// Generated by \`sbwp types\` from ${basename(manifest)}. Don't edit it: \`sbwp dev\` and \`sbwp types\` rewrite it.`,
        ...app.routes.map(
            (r, i) => `import type { handler as r${i} } from '${importPath(r.handler)}';`
        ),
        '',
        `/** Every ${app.name} route, for \`createClient<Routes>()\`. */`,
        'export type Routes = {',
        ...app.routes.map((r, i) => `    '${r.method} ${r.path}': typeof r${i};`),
        '};',
        ''
    ];
    return lines.join('\n');
};

export type TypesResult = { readonly file: string; readonly changed: boolean };

/**
 * Writes the routes types for an app. With `check`, writes nothing and reports whether the
 * committed file is out of date.
 */
export const writeRoutesTypes = async (options: {
    readonly appDir: string;
    readonly manifest?: string;
    readonly check?: boolean;
    readonly app?: AppManifest;
}): Promise<TypesResult> => {
    const manifest = options.manifest ?? DEFAULT_MANIFEST;
    const app = options.app ?? (await loadManifest(options.appDir, manifest));
    const file = typesFile(manifest);
    const content = routesTypes(app, manifest);
    const current = await readFile(join(options.appDir, file), 'utf8').catch(() => undefined);
    const changed = current !== content;
    if (changed && !options.check) {
        await writeFile(join(options.appDir, file), content);
    }
    return { file, changed };
};
